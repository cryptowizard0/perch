#!/bin/sh
# Embeds packaging/dsh/perch.mjs (the dsh plugin, #75) into PerchSetup, so every perch and Perch.app carries the
# plugin that matches it and setup can write it next to the perch binary (#76). Edit the .mjs, then run this and
# commit both; DshPluginTests fails while they differ.
#   scripts/dsh/embed-plugin.sh
set -eu
cd "$(dirname "$0")/../.."
src=packaging/dsh/perch.mjs
out=Sources/PerchSetup/DshPluginSource.swift
if [ -n "$(tail -c 1 "$src")" ]; then
  echo "embed-plugin: $src must end with a newline" >&2
  exit 1
fi
if grep -q '"####' "$src"; then
  echo "embed-plugin: $src contains \"####, which would end the raw string; pick a longer delimiter" >&2
  exit 1
fi
{
  echo "// Generated by scripts/dsh/embed-plugin.sh from $src. Do not edit: edit the .mjs and rerun the script."
  echo ""
  echo "extension DshPlugin {"
  echo "    /// The plugin's source, byte for byte."
  echo "    public static let source = ####\"\"\""
  cat "$src"
  echo ""  # the line break before the closing delimiter is not part of the string: keep the file's last newline
  echo "\"\"\"####"
  echo "}"
} > "$out"
echo "wrote $out"
