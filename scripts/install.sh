#!/bin/sh
# Installs Perch from this checkout the way a download installs: Perch.app into $APPDIR (default ~/Applications),
# then opens it. The app does the rest on launch: copies perch + perchd into ~/.perch/bin (the fixed location every
# hook and the launchd agent run), installs perchd as a launchd agent, and on a first run asks in the notch which
# agents to connect. Nothing in an agent's config changes before you click Connect.
# Upgrading (Perch already in ~/.perch/bin, or a v0.3 install in ~/.local/bin): a development build keeps its
# version number, which the app goes by, so the script runs the bundled `perch setup --upgrade` to copy the new
# binaries, restart perchd and repair connected agents' hooks. It connects nothing new.
# perch / perchd are linked into $PREFIX (default ~/.local/bin) for typing.
# Re-run after pulling to upgrade. Undo: right-click the notch → Uninstall Perch…, or `perch uninstall`.
set -eu
cd "$(dirname "$0")/.."
PREFIX=${PREFIX:-$HOME/.local/bin}
APPDIR=${APPDIR:-$HOME/Applications}
INSTALLED=$HOME/.perch/bin
APP="$APPDIR/Perch.app"

# Only an app in an Applications folder, run without PERCH_HOME, maintains the install.
case "$APPDIR" in
    /Applications | "$HOME/Applications") ;;
    *) echo "install.sh: APPDIR must be /Applications or ~/Applications (Perch installs nothing from elsewhere)" >&2; exit 1 ;;
esac
if [ -n "${PERCH_HOME:-}" ]; then
    echo "install.sh: unset PERCH_HOME (it is for development; an app run with it installs nothing)" >&2
    exit 1
fi

# A v0.3 install: perch copied into ~/.local/bin (every Perch binary carries the todo.md mirror's header).
old_install() {
    [ -f "$PREFIX/perch" ] && [ ! -L "$PREFIX/perch" ] && grep -q "Generated by perchd. Read-only" "$PREFIX/perch"
}

mkdir -p "$APPDIR"
osascript -e 'quit app id "dev.perch.app"' >/dev/null 2>&1 || true
APP="$APP" scripts/bundle-app.sh >/dev/null
echo "installed Perch.app → $APPDIR"

if [ -x "$INSTALLED/perch" ] || old_install; then
    "$APP/Contents/Helpers/perch" setup --upgrade
fi

mkdir -p "$PREFIX"
for name in perch perchd; do
    if [ -e "$PREFIX/$name" ] || [ -L "$PREFIX/$name" ]; then
        case "$(readlink "$PREFIX/$name" || true)" in
            "$INSTALLED/$name") continue ;;
            *) echo "$PREFIX/$name is not Perch's link; left it alone" >&2; continue ;;
        esac
    fi
    ln -s "$INSTALLED/$name" "$PREFIX/$name"
    echo "linked $PREFIX/$name → $INSTALLED/$name"
done

open "$APP"
